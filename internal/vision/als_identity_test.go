// alsBF16Copy writes a copy of the checkpoint directory dir whose model.safetensors holds every F32 tensor as BF16 (nearest-even),
// so a tiny f32 fixture can exercise the 16-bit alias path; the other files are copied as they are.
func alsBF16Copy(t *testing.T, dir string) string {
	t.Helper()
	out := t.TempDir()
	ents, err := os.ReadDir(dir)
	if err != nil {
		t.Fatal(err)
	}
	for _, e := range ents {
		b, err := os.ReadFile(filepath.Join(dir, e.Name()))
		if err != nil {
			t.Fatal(err)
		}
		if e.Name() == "model.safetensors" {
			b = alsToBF16(t, b)
		}
		if err := os.WriteFile(filepath.Join(out, e.Name()), b, 0o644); err != nil {
			t.Fatal(err)
		}
	}
	return out
}

func alsToBF16(t *testing.T, b []byte) []byte {
	n := binary.LittleEndian.Uint64(b[:8])
	var hdr map[string]json.RawMessage
	if err := json.Unmarshal(b[8:8+n], &hdr); err != nil {
		t.Fatal(err)
	}
	data := b[8+n:]
	type ent struct {
		DType   string `json:"dtype"`
		Shape   []int  `json:"shape"`
		Offsets [2]int `json:"data_offsets"`
	}
	var names []string
	ents := map[string]ent{}
	for k, v := range hdr {
		if k == "__metadata__" {
			continue
		}
		var e ent
		if err := json.Unmarshal(v, &e); err != nil {
			t.Fatal(err)
		}
		ents[k], names = e, append(names, k)
	}
	sort.Slice(names, func(i, j int) bool { return ents[names[i]].Offsets[0] < ents[names[j]].Offsets[0] })
	newHdr := map[string]any{}
	var body []byte
	for _, k := range names {
		e := ents[k]
		raw := data[e.Offsets[0]:e.Offsets[1]]
		if e.DType == "F32" {
			conv := make([]byte, len(raw)/2)
			for i := 0; i < len(raw)/4; i++ {
				binary.LittleEndian.PutUint16(conv[2*i:], linalg.F32ToBF16(math.Float32frombits(binary.LittleEndian.Uint32(raw[4*i:]))))
			}
			raw, e.DType = conv, "BF16"
		}
		newHdr[k] = map[string]any{"dtype": e.DType, "shape": e.Shape, "data_offsets": []int{len(body), len(body) + len(raw)}}
		body = append(body, raw...)
	}
	h, err := json.Marshal(newHdr)
	if err != nil {
		t.Fatal(err)
	}
	for (8+len(h))%8 != 0 { // keep the payload 8-byte aligned, as HF's writer does
		h = append(h, ' ')
	}
	out := make([]byte, 8, 8+len(h)+len(body))
	binary.LittleEndian.PutUint64(out, uint64(len(h)))
	return append(append(out, h...), body...)
}

// alsTower is one newQMat tower for ALS-G1: its tiny fixture and a run that loads it (quant=false), forwards fixed inputs and
// closes it, returning the outputs and the forward after Close's error.
type alsTower struct {
	name, dir string
	run       func(t *testing.T, dir string) (out []float32, afterClose error)
}

// TestALS_G1_identity is MEM4(a)'s ALS-G1 (goinfer docs/tasks/task-memory-campaign-2026-10.md, "MEM4(a) gates"): each tower's
// tiny fixture, and a bf16 copy of it, loaded aliased (aliasQMat) against copied as before (aliasOffForTest); every output
// byte-equal, the aliased load wrapping at least one weight in place, and a forward after Close an error.
func TestALS_G1_identity(t *testing.T) {
	for _, tw := range alsTowers(t) {
		t.Run(tw.name, func(t *testing.T) {
			if _, err := os.Stat(tw.dir); err != nil {
				t.Skipf("no fixture: %v", err)
			}
			for _, variant := range []string{"f32", "bf16"} {
				dir := tw.dir
				if variant == "bf16" {
					dir = alsBF16Copy(t, tw.dir)
				}
				aliasOffForTest = true
				want, _ := tw.run(t, dir)
				aliasOffForTest = false
				before := aliasedForTest.Load()
				got, afterClose := tw.run(t, dir)
				n := aliasedForTest.Load() - before
				diff := 0
				for i := range want {
					if math.Float32bits(want[i]) != math.Float32bits(got[i]) {
						diff++
					}
				}
				fmt.Fprintf(os.Stderr, "[ALS-G1] %s %s: %d weights aliased, %d of %d outputs differ; forward after Close: %v\n", tw.name, variant, n, diff, len(want), afterClose)
				if len(want) != len(got) || diff != 0 {
					t.Errorf("%s: %d of %d outputs differ aliased against copied", variant, diff, len(want))
				}
				if n == 0 {
					t.Errorf("%s: the aliased load wrapped no weight in place", variant)
				}
				if afterClose == nil {
					t.Errorf("%s: a forward after Close returned no error", variant)
				}
			}
		})
	}
}

func alsTowers(t *testing.T) []alsTower {
	golden := func(t *testing.T, name string, v any) {
		raw, err := os.ReadFile(filepath.Join("testdata", name))
		if err != nil {
			t.Skipf("no golden: %v", err)
		}
		if err := json.Unmarshal(raw, v); err != nil {
			t.Fatal(err)
		}
	}
	synth := func(n int) []float32 { // deterministic patch values in [0, 1]
		v := make([]float32, n)
		for i := range v {
			v[i] = float32(0.5 + 0.5*math.Sin(float64(i)*0.37))
		}
		return v
	}
	g4dir := os.Getenv("ALS_G4_DIR") // goinfer's testdata/gemma4-vision-tiny (generated by goinfer's scripts/pin_gemma4_vision.py)
	if g4dir == "" {
		g4dir = "testdata/gemma4-vision-tiny"
	}
	return []alsTower{
		{"pixtral", "testdata/pixtral-vision-tiny", func(t *testing.T, dir string) ([]float32, error) {
			e, err := LoadPixtralVisionEncoder(dir, false)
			if err != nil {
				t.Fatal(err)
			}
			grids := [][2]int{{2, 3}}
			px := synth(6 * e.Cfg.NumChannels * e.Cfg.PatchSize * e.Cfg.PatchSize)
			out, err := e.Forward(px, grids)
			if err != nil {
				t.Fatal(err)
			}
			e.Close()
			_, after := e.Forward(px, grids)
			return out, after
		}},
		{"siglip2-naflex", "testdata/siglip2-naflex-tiny", func(t *testing.T, dir string) ([]float32, error) {
			e, err := LoadSiglip2NaFlexEncoder(dir, false)
			if err != nil {
				t.Fatal(err)
			}
			grid := [2]int{3, 4}
			px := synth(12 * e.Cfg.NumChannels * e.Cfg.PatchSize * e.Cfg.PatchSize)
			out, err := e.Forward(px, grid)
			if err != nil {
				t.Fatal(err)
			}
			e.Close()
			_, after := e.Forward(px, grid)
			return out, after
		}},
		{"gemma4", g4dir, func(t *testing.T, dir string) ([]float32, error) {
			e, err := LoadGemma4Encoder(dir, false)
			if err != nil {
				t.Fatal(err)
			}
			k := e.Cfg.PoolingKernelSize
			var pos [][2]int
			for y := range 2 * k {
				for x := range 2 * k {
					pos = append(pos, [2]int{x, y})
				}
			}
			px := synth(len(pos) * 3 * e.Cfg.PatchSize * e.Cfg.PatchSize)
			out, err := e.Forward(px, pos)
			if err != nil {
				t.Fatal(err)
			}
			e.Close()
			_, after := e.Forward(px, pos)
			return out, after
		}},
		{"glm-ocr", "testdata/glm-ocr-vision-tiny", func(t *testing.T, dir string) ([]float32, error) {
			var g struct {
				GridTHW     [][3]int  `json:"grid_thw"`
				PixelValues []float32 `json:"pixel_values"`
			}
			golden(t, "glm_ocr_vision_golden.json", &g)
			e, err := LoadGlmOcrVisionEncoder(dir, false)
			if err != nil {
				t.Fatal(err)
			}
			out, err := e.Forward(g.PixelValues, g.GridTHW)
			if err != nil {
				t.Fatal(err)
			}
			e.Close()
			_, after := e.Forward(g.PixelValues, g.GridTHW)
			return out, after
		}},
		{"qwen3.5", "testdata/qwen35vl-vision-tiny", func(t *testing.T, dir string) ([]float32, error) {
			g := readQwen3Golden(t, "testdata/qwen35vl_vision_golden.json")
			e, err := LoadQwen3VisionEncoder(dir, false)
			if err != nil {
				t.Fatal(err)
			}
			out, err := e.Forward(g.PixelValues, g.GridTHW)
			if err != nil {
				t.Fatal(err)
			}
			e.Close()
			_, after := e.Forward(g.PixelValues, g.GridTHW)
			return out, after
		}},
		{"qwen3-vl (DeepStack)", "testdata/qwen3vl-vision-tiny", func(t *testing.T, dir string) ([]float32, error) {
			e, err := LoadQwen3VisionEncoder(dir, false)
			if err != nil {
				t.Fatal(err)
			}
			c := e.Cfg
			grid := [][3]int{{1, 4, 4}}
			px := make([]float32, 16*c.InChannels*c.TemporalPatchSize*c.PatchSize*c.PatchSize)
			for i := range px {
				px[i] = float32(math.Sin(float64(i) * 0.37))
			}
			merged, deep, err := e.ForwardDeepstack(px, grid)
			if err != nil {
				t.Fatal(err)
			}
			out := append([]float32(nil), merged...)
			for _, d := range deep {
				out = append(out, d...)
			}
			e.Close()
			_, _, after := e.ForwardDeepstack(px, grid)
			return out, after
		}},
		{"siglip", "testdata/siglip-tiny", func(t *testing.T, dir string) ([]float32, error) {
			var g struct {
				PixelValues []float32 `json:"pixel_values"`
			}
			golden(t, "siglip_vision_golden.json", &g)
			e, err := LoadEncoder(dir, false)
			if err != nil {
				t.Fatal(err)
			}
			out, err := e.Forward(g.PixelValues)
			if err != nil {
				t.Fatal(err)
			}
			e.Close()
			_, after := e.Forward(g.PixelValues)
			return out, after
		}},
		{"qwen2.5-vl", "testdata/qwen25vl-vision-tiny", func(t *testing.T, dir string) ([]float32, error) {
			raw, err := os.ReadFile("testdata/qwen25vl_vision_golden.json")
			if err != nil {
				t.Skipf("no golden: %v", err)
			}
			var g struct {
				GridTHW     [][3]int  `json:"grid_thw"`
				PixelValues []float32 `json:"pixel_values"`
			}
			if err := json.Unmarshal(raw, &g); err != nil {
				t.Fatal(err)
			}
			e, err := LoadQwenVisionEncoder(dir, false)
			if err != nil {
				t.Fatal(err)
			}
			out, err := e.Forward(g.PixelValues, g.GridTHW)
			if err != nil {
				t.Fatal(err)
			}
			e.Close()
			_, after := e.Forward(g.PixelValues, g.GridTHW)
			return out, after
		}},
	}
}
