// f32Walk calls fn on every []float32 reachable from v (structs, slices, pointers), for summing and hashing a weight export.
func f32Walk(v reflect.Value, fn func([]float32)) {
	switch v.Kind() {
	case reflect.Pointer, reflect.Interface:
		if !v.IsNil() {
			f32Walk(v.Elem(), fn)
		}
	case reflect.Struct:
		for i := range v.NumField() {
			if v.Type().Field(i).IsExported() {
				f32Walk(v.Field(i), fn)
			}
		}
	case reflect.Slice:
		if v.Type().Elem().Kind() == reflect.Float32 {
			fn(v.Interface().([]float32))
			return
		}
		for i := range v.Len() {
			f32Walk(v.Index(i), fn)
		}
	}
}

// exportSig is an export's float32 byte count and a hash of its bits.
func exportSig(w any) (bytes int, hash uint64) {
	hash = 1469598103934665603
	f32Walk(reflect.ValueOf(w), func(s []float32) {
		bytes += 4 * len(s)
		for _, x := range s {
			hash = (hash ^ uint64(math.Float32bits(x))) * 1099511628211
		}
	})
	return bytes, hash
}

// must calls an export and fails the test on its error.
func must[W any](t *testing.T, f func() (W, error)) W {
	t.Helper()
	w, err := f()
	if err != nil {
		t.Fatal(err)
	}
	return w
}

func heapInUse() int64 {
	runtime.GC()
	runtime.GC()
	var m runtime.MemStats
	runtime.ReadMemStats(&m)
	return int64(m.HeapAlloc)
}

// releasable is one tower under TWR-G1: its forward on a fixed input, its export's blocks and whole export, and the release.
type releasable struct {
	name     string
	forward  func() ([]float32, error)
	blocks   func() any // the export's blocks (or layers) alone, for their byte count
	export   func() any
	release  func() error
	released func() bool
}

func pixels(n int) []float32 {
	px := make([]float32, n)
	for i := range px {
		px[i] = float32(math.Sin(float64(i) * 0.37))
	}
	return px
}

func releasables(t *testing.T) []releasable {
	t.Helper()
	var out []releasable
	if e, err := LoadQwen3VisionEncoder("testdata/qwen35vl-vision-tiny", false); err == nil {
		c := e.Cfg
		g := [][3]int{{1, 4, 4}}
		px := pixels(16 * c.InChannels * c.TemporalPatchSize * c.PatchSize * c.PatchSize)
		out = append(out, releasable{"qwen3.5", func() ([]float32, error) { return e.Forward(px, g) },
			func() any { return must(t, e.Weights).Blocks }, func() any { return must(t, e.Weights) },
			e.ReleaseBlocks, e.BlocksReleased})
	} else {
		t.Logf("no Qwen3.5 tiny tower: %v", err)
	}
	if e, err := LoadGlmOcrVisionEncoder(glmTinyCkpt, false); err == nil {
		c := e.Cfg
		g := [][3]int{{1, 4, 4}}
		px := pixels(16 * c.InChannels * c.TemporalPatchSize * c.PatchSize * c.PatchSize)
		out = append(out, releasable{"glm-ocr", func() ([]float32, error) { return e.Forward(px, g) },
			func() any { return must(t, e.Weights).Blocks }, func() any { return must(t, e.Weights) },
			e.ReleaseBlocks, e.BlocksReleased})
	} else {
		t.Logf("no GLM-OCR tiny tower: %v", err)
	}
	if e, err := LoadQwenVisionEncoder("testdata/qwen25vl-vision-tiny", false); err == nil {
		c := e.Cfg
		g := [][3]int{{1, 8, 8}}
		px := pixels(64 * c.InChans * c.TemporalPatchSize * c.PatchSize * c.PatchSize)
		out = append(out, releasable{"qwen2.5-vl", func() ([]float32, error) { return e.Forward(px, g) },
			func() any { return e.GPUWeights().Blocks }, func() any { return e.GPUWeights() },
			e.ReleaseBlocks, e.BlocksReleased})
	} else {
		t.Logf("no Qwen2.5-VL tiny tower: %v", err)
	}
	if dir := filepath.Join("testdata", "gemma4-vision-tiny"); func() bool { _, err := os.Stat(dir); return err == nil }() {
		e, err := LoadGemma4Encoder(dir, false)
		if err != nil {
			t.Fatal(err)
		}
		c := e.Cfg
		k := c.PoolingKernelSize
		var pos [][2]int
		for y := range 2 * k {
			for x := range 2 * k {
				pos = append(pos, [2]int{x, y})
			}
		}
		px := pixels(len(pos) * 3 * c.PatchSize * c.PatchSize)
		for i := range px {
			px[i] = 0.5 + 0.5*px[i] // the tower takes patches in [0, 1]
		}
		out = append(out, releasable{"gemma4", func() ([]float32, error) { return e.Forward(px, pos) },
			func() any { return must(t, e.Weights).Layers }, func() any { return must(t, e.Weights) },
			e.ReleaseBlocks, e.BlocksReleased})
	} else {
		t.Logf("no gemma4-vision-tiny (generated by goinfer's scripts/pin_gemma4_vision.py): Gemma 4 not covered on this run")
	}
	if len(out) < 3 {
		t.Fatalf("only %d towers loaded; the gate needs aikit's three tracked tiny towers", len(out))
	}
	return out
}

// TestReleaseBlocks_reloadsTheSameTower is TWR-G1 (goinfer's docs/tasks/task-memory-campaign-2026-10.md, MEM4(b) gates):
// after ReleaseBlocks the heap falls by at least 80% of the blocks' bytes, the next forward is byte-equal to the one before
// and reloads the blocks, and the export after it hashes the same as before.
//
// It runs twice: with the blocks copied onto the heap (aliasOffForTest), where the heap check above is the point, and with
// them aliased in the checkpoint mapping (MEM4(a)), where the blocks were never on the heap and only the reload, the forward
// and the export are checked.
func TestReleaseBlocks_reloadsTheSameTower(t *testing.T) {
	defer func() { aliasOffForTest = false }()
	for _, aliasOff := range []bool{true, false} {
		aliasOffForTest = aliasOff
		mode := map[bool]string{true: "copied", false: "aliased"}[aliasOff]
		for _, r := range releasables(t) {
			t.Run(mode+"/"+r.name, func(t *testing.T) {
				before, err := r.forward()
				if err != nil {
					t.Fatal(err)
				}
				blockBytes, _ := exportSig(r.blocks())
				_, sig := exportSig(r.export())
				h0 := heapInUse()
				if err := r.release(); err != nil {
					t.Fatal(err)
				}
				h1 := heapInUse()
				if !r.released() {
					t.Error("BlocksReleased is false right after ReleaseBlocks")
				}
				freed := h0 - h1
				t.Logf("%s: blocks %d bytes; heap %d -> %d (freed %d, %.0f%%)", r.name, blockBytes, h0, h1, freed, 100*float64(freed)/float64(blockBytes))
				if aliasOff && float64(freed) < 0.8*float64(blockBytes) {
					t.Errorf("the release freed %d bytes of the blocks' %d (under 80%%)", freed, blockBytes)
				}
				after, err := r.forward()
				if err != nil {
					t.Fatalf("forward after the release: %v", err)
				}
				if r.released() {
					t.Error("BlocksReleased is still true after a forward reloaded them")
				}
				if len(after) != len(before) {
					t.Fatalf("forward after the release: %d values, want %d", len(after), len(before))
				}
				for i := range before {
					if math.Float32bits(before[i]) != math.Float32bits(after[i]) {
						t.Fatalf("forward after the release differs at %d: %v against %v", i, after[i], before[i])
					}
				}
				if _, sig2 := exportSig(r.export()); sig2 != sig {
					t.Error("the export after the release differs from the one before")
				}
			})
		}
	}
}

// TestReleaseBlocks_refusesACallersSource: a tower built from a caller's TensorSource cannot reopen it, so ReleaseBlocks
// refuses and the tower keeps working.
func TestReleaseBlocks_refusesACallersSource(t *testing.T) {
	ref, err := LoadQwen3VisionEncoder("testdata/qwen35vl-vision-tiny", false)
	if err != nil {
		t.Skipf("no Qwen3.5 tiny tower: %v", err)
	}
	st, err := openWeights("testdata/qwen35vl-vision-tiny")
	if err != nil {
		t.Fatal(err)
	}
	defer st.Close()
	e, err := LoadQwen3VisionEncoderFrom(ref.Cfg, prefixedSource{st, qwen3TensorPrefix(st)}, false)
	if err != nil {
		t.Fatal(err)
	}
	if err := e.ReleaseBlocks(); err == nil {
		t.Fatal("ReleaseBlocks on a caller's-source tower returned nil")
	}
	if e.BlocksReleased() {
		t.Error("a refused release reports the blocks released")
	}
	g := [][3]int{{1, 4, 4}}
	c := e.Cfg
	if _, err := e.Forward(pixels(16*c.InChannels*c.TemporalPatchSize*c.PatchSize*c.PatchSize), g); err != nil {
		t.Errorf("forward after a refused release: %v", err)
	}
}
