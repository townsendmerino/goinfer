// S8 (docs/tasks/task-multimodal-support-2026-10.md, "S8, plan and gates"): the images-and-audio support table in
// docs/multimodal.md and the README, generated here. Every tower / decoder cell is computed from code:
//   - tower: GPU when the backend's build declares that tower family (multimodal.DeclaredTower; each backend module's test
//     proves its live registrations equal the declaration);
//   - decoder: GPU when an image turn decodes on the backend's resident (imageTurnDecodesResident: ResidentEligible, the
//     hybrid image prefill declaration, Gemma 4's rule).
//
// The notes are what the code cannot answer (validation, memory, speed), each with a date. Regenerate with
// `go test ./decoder -run SupportTable -update`; the test fails when either file's block differs from the generated one.

const (
	supportBegin = "<!-- BEGIN images-and-audio support table: generated by `go test ./decoder -run SupportTable -update` (decoder/support_table_test.go); the cells are computed from code, edit the notes there -->"
	supportEnd   = "<!-- END images-and-audio support table -->"
)

// supportBackends are the table's columns, in order (decoder's backend names; "cpu" is the CPU column).
var supportBackends = []struct{ name, label string }{{"cpu", "CPU"}, {"cuda", "CUDA"}, {"metal", "Metal"}, {"webgpu", "WebGPU"}}

// supportRow is one family of the table: its label, the model_type serve dispatches on, its tower family, the config its
// decoder cells are computed from, and the notes.
type supportRow struct {
	label, modelType, tower string
	cfg                     func(t *testing.T) *Config
	notes                   string
}

func rep(mt string, edit func(*Config)) func(t *testing.T) *Config {
	return func(t *testing.T) *Config {
		c := representativeConfig(mt)
		if c == nil {
			t.Fatalf("no representative config for %q", mt)
		}
		if edit != nil {
			edit(c)
		}
		return c
	}
}

