// supportCell computes one tower / decoder cell.
func supportCell(t *testing.T, row supportRow, backend string) string {
	if backend == "cpu" {
		return "CPU / CPU"
	}
	tower := "CPU"
	if multimodal.DeclaredTower(backend, row.tower) {
		tower = "GPU"
	}
	cfg := row.cfg(t)
	a, _, err := resolveArchitecture(cfg)
	if err != nil {
		t.Fatalf("%s: resolve: %v", row.label, err)
	}
	dec := "CPU"
	if imageTurnDecodesResident(cfg, a, backend) {
		dec = "GPU"
	}
	return tower + " / " + dec
}

// generateSupportTable renders the block: withNotes for docs/multimodal.md, without for the README.
func generateSupportTable(t *testing.T, withNotes bool) string {
	var b strings.Builder
	b.WriteString(supportBegin + "\n\n")
	b.WriteString("Each cell: where the image or audio **tower** runs / where the **decoder** runs after the image.\n\n")
	head, sep := "| family (`model_type`) |", "|---|"
	for _, be := range supportBackends {
		head += " " + be.label + " |"
		sep += "---|"
	}
	if withNotes {
		head += " notes |"
		sep += "---|"
	}
	b.WriteString(head + "\n" + sep + "\n")
	for _, row := range supportRows {
		line := fmt.Sprintf("| %s (`%s`) |", row.label, row.modelType)
		for _, be := range supportBackends {
			line += " " + supportCell(t, row, be.name) + " |"
		}
		if withNotes {
			line += " " + row.notes + " |"
		}
		b.WriteString(line + "\n")
	}
	b.WriteString("\n" + supportEnd)
	return b.String()
}

// spliceSupportBlock returns doc with its BEGIN..END block replaced by block, and whether the doc had one.
func spliceSupportBlock(doc, block string) (string, bool) {
	i := strings.Index(doc, supportBegin)
	j := strings.Index(doc, supportEnd)
	if i < 0 || j < i {
		return doc, false
	}
	return doc[:i] + block + doc[j+len(supportEnd):], true
}

// TestSupportTable_fresh (G-S8a): docs/multimodal.md's and the README's support tables equal the generated ones.
func TestSupportTable_fresh(t *testing.T) {
	t.Setenv("GOINFER_SSM_RESIDENT", "") // the hardware matrix's own pin (ResidentEligible's granite gate reads it)
	for _, f := range []struct {
		path      string
		withNotes bool
	}{{"../docs/multimodal.md", true}, {"../README.md", false}} {
		raw, err := os.ReadFile(f.path)
		if err != nil {
			t.Fatal(err)
		}
		want := generateSupportTable(t, f.withNotes)
		got, ok := spliceSupportBlock(string(raw), want)
		if !ok {
			t.Errorf("%s has no support-table block (%q ... %q)", f.path, supportBegin[:30], supportEnd)
			continue
		}
		if *updateMatrix {
			if err := os.WriteFile(f.path, []byte(got), 0o644); err != nil {
				t.Fatal(err)
			}
			continue
		}
		if !bytes.Equal(raw, []byte(got)) {
			t.Errorf("%s: the support table is stale; regenerate with `go test ./decoder -run SupportTable -update`\n%s", f.path, want)
		}
	}
}

// TestSupportTable_plantedDefects (G-S8b): the drift each piece of the check exists for turns a cell, so the
// generated-and-compared table would go red. Each mutation is applied to the computation, not to the file.
func TestSupportTable_plantedDefects(t *testing.T) {
	t.Setenv("GOINFER_SSM_RESIDENT", "")
	byLabel := map[string]supportRow{}
	for _, r := range supportRows {
		byLabel[r.label] = r
	}
	// This morning's real error: Qwen3.5+ on Metal decoding an image turn on the GPU. The cell must read CPU, and a
	// Metal hybrid image prefill (a declaration that would make it GPU) is not declared.
	if got := supportCell(t, byLabel["Qwen3.5+ dense"], "metal"); got != "GPU / CPU" {
		t.Errorf("Qwen3.5+ dense on Metal: %q, want GPU / CPU (the tower is Metal's, the image turn decodes on the CPU)", got)
	}
	if HybridImagePrefillDeclared("metal", false) {
		t.Error("a hybrid image prefill is declared for Metal, which implements none")
	}
	if got := supportCell(t, byLabel["Qwen3.5+ dense"], "cuda"); got != "GPU / GPU" {
		t.Errorf("Qwen3.5+ dense on CUDA: %q, want GPU / GPU (CUDA builds a dense hybrid's state in its image prefill)", got)
	}
	// A WebGPU Gemma 4 tower is not declared: the cell must read CPU for the tower.
	if got := supportCell(t, byLabel["Gemma 4 E2B, E4B"], "webgpu"); !strings.HasPrefix(got, "CPU / ") {
		t.Errorf("Gemma 4 on WebGPU: %q, want a CPU tower", got)
	}
	// A causal, non-E Gemma 4 decodes on the CPU after an image, whatever the backend.
	causal := supportRow{label: "causal Gemma 4", tower: multimodal.TowerGemma4, cfg: rep("gemma4", nil)}
	if got := supportCell(t, causal, "cuda"); strings.HasSuffix(got, "/ GPU") {
		t.Errorf("a causal, non-E Gemma 4 on CUDA: %q, want a CPU decoder after an image", got)
	}
	// A README cell that differs from the doc's: the two blocks share every cell, so one edited cell differs.
	doc, readme := generateSupportTable(t, true), generateSupportTable(t, false)
	if !strings.Contains(doc, "| Qwen3.5+ dense (`qwen3_5`) | CPU / CPU | GPU / GPU | GPU / CPU | CPU / CPU |") ||
		!strings.Contains(readme, "| Qwen3.5+ dense (`qwen3_5`) | CPU / CPU | GPU / GPU | GPU / CPU | CPU / CPU |") {
		t.Errorf("the README and doc blocks do not carry the same Qwen3.5+ row:\n%s\n%s", doc, readme)
	}
	mutated, _ := spliceSupportBlock(supportBegin+"\n"+supportEnd, strings.Replace(readme, "GPU / CPU", "GPU / GPU", 1))
	if mutated == readme {
		t.Error("a mutated README cell compares equal: the freshness check could not see it")
	}
}
