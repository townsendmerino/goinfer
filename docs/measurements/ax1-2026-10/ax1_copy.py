#!/usr/bin/env python3
"""AX1: copy aikit's towers and GPU backends into goinfer, or check that the copy still matches.

    ax1_copy.py copy  <aikit-root-snapshot> <aikit-gpu-snapshot> <goinfer-root>
    ax1_copy.py check <aikit-root-snapshot> <aikit-gpu-snapshot> <goinfer-root>

The snapshots are `git archive` extractions of aikit at root v1.75.0 and at gpu/v0.35.0 (tracked files only).
`copy` writes every moved file with the rewrite below applied; `check` (gate AX1-S) recomputes each file from the
snapshot and fails on any byte that differs, and on any file in a destination directory that the copy did not write;
the files in EDITED_AFTER_COPY are listed, not compared.
The rewrite is the whole of the change: import paths, the gpudev package clause, and fixture paths.
"""
import os
import re
import shutil
import subprocess
import sys

GI = "github.com/townsendmerino/goinfer"
AK = "github.com/townsendmerino/aikit"

# (snapshot key, source dir, destination dir, fixture-path rewrite or device-package half)
PACKAGES = [
    ("root", "vision", "internal/vision", "vision"),
    ("root", "audio", "internal/audio", None),
    ("gpu", "gpu", "cuda/internal/gpudev", "cuda"),
    ("gpu", "gpu", "metal/internal/gpudev", "metal"),
    ("gpu", "gpu/qwencuda", "cuda/internal/qwencuda", "backend"),
    ("gpu", "gpu/visioncuda", "cuda/internal/visioncuda", "backend"),
    ("gpu", "gpu/qwenmetal", "metal/internal/qwenmetal", "backend"),
    ("gpu", "gpu/visionmetal", "metal/internal/visionmetal", "backend"),
]
# The device package splits by backend, so the root module never compiles purego or gocudrv (ci.yml's cleanliness
# guard): a file built only on linux goes to the cuda module, one built only on darwin to the metal module, and the
# rest (untagged, `darwin || linux`, `!darwin && !linux`) to both, except as SPLIT_ONLY says.
SPLIT_ONLY = {
    "kernel_fma_lint_test.go": "cuda", "ptx_reproducible_test.go": "cuda",  # read the .cu and .ptx files
    "outputcontract_doc_test.go": "metal",  # reads both halves' sources; the cuda half's by relative path
}
CUDA_HALF_FROM_METAL = "../../../cuda/internal/gpudev/"
# Sub-directories of gpu/ that are their own modules and are not part of the device package.
GPU_SUBMODULES = {"qwencuda", "visioncuda", "qwenmetal", "visionmetal", "webgpu",
                  "anncuda", "annmetal", "enccuda", "encmetal"}
SKIP_FILES = {"go.mod", "go.sum"}

# aikit testdata the moved vision tests read, copied byte for byte into internal/vision/testdata.
VISION_FIXTURES = [
    "bicubic-resize", "glm-ocr-vision-tiny", "glm_ocr_vision_golden.json", "pixtral-vision-tiny",
    "pixtral_vision_golden.json", "qwen25vl-vision-tiny", "qwen25vl_vision_golden.json", "qwen35vl-vision-tiny",
    "qwen35vl_vision_golden.json", "qwen3vl-vision-tiny", "siglip-tiny", "siglip2-naflex-tiny",
    "siglip2_naflex_golden.json", "siglip_vision_golden.json", "gemma4_vision_golden.json",
    "gemma4_vision_real_26b_golden.json.gz", "gemma4_vision_real_golden.json.gz",
]
# The oracle scripts that pinned those goldens, kept beside them for provenance (unchanged; their paths are aikit's).
VISION_ORACLES = ["pin_bicubic_resize.py", "pin_qwen25vl_vision.py", "pin_qwen35_vision.py",
                  "pin_siglip_vision.py", "gen_siglip_bench.py"]
# aikit does not track gemma4-vision-tiny (its tests skip without it); goinfer does, generated by the same
# scripts/pin_gemma4_vision.py, so the moved tests read goinfer's copy.
GOINFER_FIXTURES = ["gemma4-vision-tiny"]
# Copied files edited after the copy commit, each with why; `check` lists them instead of comparing their bytes.
EDITED_AFTER_COPY = {
    "metal/internal/gpudev/residencyset_test.go": "skips when the device makes no residency set (hosted CI runner)",
    "cuda/internal/visioncuda/encoder_test.go": "graphCapture skips when there is no CUDA device (GPU-less CI runner)",
}

IMPORTS = [
    (f'"{AK}/gpu/visionmetal"', f'"{GI}/metal/internal/visionmetal"'),
    (f'"{AK}/gpu/qwenmetal"', f'"{GI}/metal/internal/qwenmetal"'),
    (f'"{AK}/gpu/visioncuda"', f'"{GI}/cuda/internal/visioncuda"'),
    (f'"{AK}/gpu/qwencuda"', f'"{GI}/cuda/internal/qwencuda"'),
    (f'"{AK}/vision"', f'"{GI}/internal/vision"'),
    (f'"{AK}/audio"', f'"{GI}/internal/audio"'),
]
GPU_IMPORT = re.compile(r'^(\s*)(\w+ )?"' + re.escape(AK) + r'/gpu"', re.M)


def rewrite_go(text, dest, fixtures):
    for old, new in IMPORTS:
        text = text.replace(old, new)
    # The device package is named gpudev, one half in each backend module; importers keep the identifier gpu, so
    # their bodies are unchanged.
    half = "cuda" if dest.startswith("cuda/") else "metal"
    text = GPU_IMPORT.sub(lambda m: f'{m.group(1)}{m.group(2) or "gpu "}"{GI}/{half}/internal/gpudev"', text)
    if dest.endswith("internal/gpudev"):
        text = re.sub(r"^package gpu(_test)?$", lambda m: "package gpudev" + (m.group(1) or ""), text, flags=re.M)
        text = text.replace("// Package gpu is ", "// Package gpudev is ")
    if fixtures == "vision":
        text = text.replace('"../testdata/', '"testdata/')
        text = text.replace('filepath.Join("..", "testdata"', 'filepath.Join("testdata"')
    elif fixtures == "backend":
        text = text.replace('"../../testdata/', '"../../../internal/vision/testdata/')
    if dest == "metal/internal/gpudev":
        for name in ("cuda.go", "cuda_copy.go"):
            text = text.replace(f'"{name}"', f'"{CUDA_HALF_FROM_METAL}{name}"')
    return text


def half_of(name, data):
    """Which device-package half(s) a file of aikit's gpu/ goes to."""
    if name in SPLIT_ONLY:
        return {SPLIT_ONLY[name]}
    if not name.endswith(".go"):
        return {"cuda"}  # the .cu sources, the PTX build scripts and testdata/*.ptx
    for line in data.decode().splitlines():
        if line.startswith("//go:build "):
            expr = line[len("//go:build "):].strip()
            return {"linux": {"cuda"}, "darwin": {"metal"}}.get(expr, {"cuda", "metal"})
        if line.startswith("package "):
            break
    return {"cuda", "metal"}


def plan(snaps, goinfer):
    """Yields (source path, destination path, rewritten bytes)."""
    for key, src, dest, fixtures in PACKAGES:
        base = os.path.join(snaps[key], src)
        for dirpath, dirnames, filenames in os.walk(base):
            rel = os.path.relpath(dirpath, base)
            if src == "gpu" and rel == ".":
                dirnames[:] = [d for d in dirnames if d not in GPU_SUBMODULES]
            for name in sorted(filenames):
                if rel == "." and name in SKIP_FILES:
                    continue
                sp = os.path.join(dirpath, name)
                dp = os.path.normpath(os.path.join(dest, rel, name))
                data = open(sp, "rb").read()
                if fixtures in ("cuda", "metal") and fixtures not in half_of(name, data):
                    continue
                if name.endswith(".go"):
                    # gofmt re-sorts an import block whose rewritten paths changed order.
                    data = subprocess.run(["gofmt"], input=rewrite_go(data.decode(), dest, fixtures).encode(),
                                          capture_output=True, check=True).stdout
                yield sp, dp, data
    for name in VISION_FIXTURES:
        yield from tree(os.path.join(snaps["root"], "testdata", name), os.path.join("internal/vision/testdata", name))
    for name in VISION_ORACLES:
        yield from tree(os.path.join(snaps["root"], "scripts/oracle", name),
                        os.path.join("internal/vision/testdata/oracle", name))
    for name in GOINFER_FIXTURES:
        yield from tree(os.path.join(goinfer, "testdata", name), os.path.join("internal/vision/testdata", name))


def tree(src, dest):
    if os.path.isfile(src):
        yield src, dest, open(src, "rb").read()
        return
    if not os.path.isdir(src):
        sys.exit(f"missing source {src}")
    for dirpath, _, filenames in os.walk(src):
        for name in sorted(filenames):
            sp = os.path.join(dirpath, name)
            yield sp, os.path.join(dest, os.path.relpath(sp, src)), open(sp, "rb").read()


def main():
    mode, root_snap, gpu_snap, goinfer = sys.argv[1:5]
    snaps = {"root": root_snap, "gpu": gpu_snap}
    files = list(plan(snaps, goinfer))
    if mode == "copy":
        for sp, dp, data in files:
            out = os.path.join(goinfer, dp)
            os.makedirs(os.path.dirname(out), exist_ok=True)
            with open(out, "wb") as f:
                f.write(data)
            shutil.copymode(sp, out)
        print(f"wrote {len(files)} files")
        return
    bad, want = 0, {dp for _, dp, _ in files}
    for _, dp, data in files:
        out = os.path.join(goinfer, dp)
        if dp in EDITED_AFTER_COPY:
            print(f"edited after the copy: {dp}: {EDITED_AFTER_COPY[dp]}")
            continue
        if not os.path.exists(out) or open(out, "rb").read() != data:
            print(f"DIFFERS: {dp}")
            bad += 1
    for _, _, dest, _ in PACKAGES:
        for dirpath, _, filenames in os.walk(os.path.join(goinfer, dest)):
            for name in filenames:
                dp = os.path.relpath(os.path.join(dirpath, name), goinfer)
                if dp not in want:
                    print(f"EXTRA: {dp}")
                    bad += 1
    print(f"{len(files)} files checked, {bad} differ")
    sys.exit(1 if bad else 0)


if __name__ == "__main__":
    main()
